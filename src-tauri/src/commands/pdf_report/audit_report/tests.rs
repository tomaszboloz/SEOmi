#[test]
fn clean_audits_are_not_empty_reports() {
    let mut audit = fixture();
    audit["issues"] = json!([]);
    let text = text_of(&audit);
    assert!(text.contains("No issues were reported by this audit."));
    assert!(text.contains("Passed checks") && text.contains("checks passed."));
}

#[test]
fn minimal_audits_still_render_every_block_without_blanks() {
    let text = text_of(&json!({"final_url": "https://example.test"}));
    for part in [
        "https://example.test",
        "Not scored",
        "No issues were reported",
        "no detailed page data",
    ] {
        assert!(text.contains(part), "missing: {part}");
    }
    assert!(!text.contains("Passed checks"));
    assert!(text.contains('\u{2014}'));
}

#[test]
fn many_findings_paginate_without_losing_any() {
    let mut audit = fixture();
    let issues: Vec<Value> = (0..45)
        .map(|n| {
            let severity = ["Critical", "Warning", "Info"][n % 3];
            json!({"severity": severity, "category": "Links", "code": "links_insecure",
                "message": format!("finding-number-{n}"), "recommendation": "Use https"})
        })
        .collect();
    audit["issues"] = json!(issues);
    let bytes = audit_pdf(&audit);
    assert!(
        String::from_utf8_lossy(&bytes)
            .matches("/Type /Page ")
            .count()
            >= 8
    );
    let text = extract_pdf_text(&bytes);
    for n in 0..45 {
        assert!(
            text.contains(&format!("finding-number-{n}")),
            "lost finding {n}"
        );
    }
}

#[test]
fn long_urls_and_unicode_text_survive_wrapping() {
    let mut audit = fixture();
    let url = format!("https://example.test/{}?q=1", "segment/".repeat(40));
    audit["final_url"] = json!(url);
    audit["issues"] = json!([{"severity": "Critical", "category": "MetaTags", "code": "meta_title_missing",
        "message": "Brak tytułu: zażółć gęślą", "recommendation": "Добавьте заголовок 你好 مرحبا"}]);
    let text = text_of(&audit);
    assert!(text.contains(&url));
    for part in ["zażółć gęślą", "Добавьте заголовок", "你好", "مرحبا"]
    {
        assert!(text.contains(part), "missing {part}");
    }
}

#[test]
fn every_image_without_alt_text_is_listed() {
    let mut audit = fixture();
    audit["images"] = json!((0..40)
        .map(|n| json!({"src": format!("https://cdn.test/img-{n}.png"), "has_alt": false}))
        .collect::<Vec<_>>());
    let text = text_of(&audit);
    for n in 0..40 {
        assert!(text.contains(&format!("img-{n}.png")), "missing image {n}");
    }
}
