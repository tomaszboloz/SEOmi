use super::audit_pdf;
use super::fixture::fixture;
use crate::commands::pdf_report::tests::extract_pdf_text;
use serde_json::{json, Value};

fn text_of(audit: &Value) -> String {
    extract_pdf_text(&audit_pdf(audit))
}

#[test]
fn report_tells_what_to_fix_and_where_for_every_finding() {
    let text = text_of(&fixture());
    for part in [
        "SEO audit report",
        "What to fix first",
        "Critical (1)",
        "Warning (2)",
        "Info (1)",
        "Missing meta description tag",
        "HOW TO FIX",
        "Add a description",
        "WHERE",
        "Page: https://example.test/page",
        "<meta name=\"description\">",
        "HTTP response header: Content-Security-Policy",
        "Image: https://cdn.test/a.png",
        "Whole page: https://example.test/page",
        "meta_description_missing",
        "Review this finding and correct the affected element.",
    ] {
        assert!(text.contains(part), "missing: {part}");
    }
    let critical = text.find("Missing meta description tag").unwrap();
    let info = text.find("Image missing alt").unwrap();
    assert!(critical < info, "findings must be sorted by severity");
}

