#[test]
fn every_page_of_a_large_crawl_is_listed_and_the_report_paginates() {
    let bytes = crawl_pdf(&synthetic(300));
    assert!(pages_of(&bytes) > 60);
    let text = extract_pdf_text(&bytes);
    for index in [1, 150, 299] {
        assert!(
            text.contains(&format!("page-{index}")),
            "missing page {index}"
        );
    }
    assert!(text.contains("... and 92 more pages"));
}

#[test]
fn minimal_runs_still_render_all_blocks_with_dashes_and_no_blanks() {
    let text = text_of(&json!({"scope_start_url": "https://example.test"}));
    for part in [
        "https://example.test",
        "Not scored",
        "No issues were found",
        "None found in this run.",
        "Report coverage",
        "Run details",
        "Crawl configuration",
        "Robots.txt and sitemap",
    ] {
        assert!(text.contains(part), "missing: {part}");
    }
    assert!(text.contains('\u{2014}'));
}
