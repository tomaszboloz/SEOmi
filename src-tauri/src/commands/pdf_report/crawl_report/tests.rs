use super::crawl_pdf;
use super::fixture::synthetic;
use crate::commands::pdf_report::tests::extract_pdf_text;
use serde_json::{json, Value};

pub(super) fn text_of(run: &Value) -> String {
    extract_pdf_text(&crawl_pdf(run))
}

fn pages_of(bytes: &[u8]) -> usize {
    String::from_utf8_lossy(bytes)
        .matches("/Type /Page ")
        .count()
}

