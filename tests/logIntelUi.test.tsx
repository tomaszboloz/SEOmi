import { cleanup, fireEvent, render, screen, waitFor, within } from '@testing-library/react';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import i18n from '@/i18n';
import LogIntelligencePanel from '@/components/Domain/crawlResults/logIntelligence/LogIntelligencePanel';
import { readLogState, saveLogState } from '@/services/logIntelligence/storage';
import * as files from '@/services/logIntelligence/browserFile';
import { coveredLogState, logFile, logLine, logRun, setupLogCrypto } from './fixtures/logIntel';

const choose = (file?: File) => fireEvent.change(screen.getByLabelText('Choose access log'), { target: { files: file ? [file] : [] } });
beforeEach(async () => { await i18n.changeLanguage('en'); localStorage.clear(); setupLogCrypto(); });
afterEach(() => { cleanup(); vi.restoreAllMocks(); vi.unstubAllGlobals(); });

describe('Log intelligence panel', () => {
  it('imports chunked local logs, shows counters, family, claimed status and error share, and never uses the network', async () => {
    const fetch = vi.spyOn(globalThis, 'fetch');
    const file = logFile([logLine('/a', 200), logLine('/a', 404), logLine('/human', 200, 'curl'), 'bad'].join('\n'));
    const whole = vi.spyOn(file, 'arrayBuffer');
    render(<LogIntelligencePanel projectId="p1" run={logRun([['/a'], ['/unseen']])} />);
    expect(screen.getByText('The latest project crawl has no saved per-path TRS scores. No scores are inferred.')).toBeTruthy();
    expect(screen.getAllByText('No logs')).toHaveLength(2);
    choose();
    expect(screen.queryByRole('progressbar')).toBeNull();
    choose(file);
    expect(screen.getByRole('progressbar')).toBeTruthy();
    await screen.findByText(/Import complete\./);
    expect(screen.getByRole('status').textContent).toContain('Lines: 4 · Malformed: 1 · Ignored non-bot: 1');
    const row = screen.getByText('/a').closest('tr')!;
    expect(within(row).getByText('Googlebot')).toBeTruthy();
    expect(within(row).getByText('Claimed')).toBeTruthy();
    expect(within(row).getByText('50%')).toBeTruthy();
    expect(within(row).getByText('Inconclusive')).toBeTruthy();
    expect(screen.getByText('Coverage: 1 of 30 days')).toBeTruthy();
    expect(screen.getByText(/Window \(UTC\):/)).toBeTruthy();
    expect(screen.getByText(/desktop DNS resolver/)).toBeTruthy();
    expect(screen.getByText('Log coverage is insufficient for reliable verdicts.')).toBeTruthy();
    expect(whole).not.toHaveBeenCalled();
    expect(fetch).not.toHaveBeenCalled();
    expect(JSON.stringify(readLogState('p1'))).not.toContain('1.2.3.4');
  });
  it('persists, dedupes renamed content after remount and clears just the active project', async () => {
    saveLogState('p2', coveredLogState());
    const first = render(<LogIntelligencePanel projectId="p1" />);
    choose(logFile(logLine()));
    await screen.findByText(/Import complete\./);
    first.unmount();
    render(<LogIntelligencePanel projectId="p1" />);
    expect(screen.getByRole('status').textContent).toContain('Lines: 1');
    choose(logFile(logLine(), 'rotated.txt'));
    await screen.findByText(/This file was already imported/);
    expect(readLogState('p1').lines).toBe(1);
    fireEvent.click(screen.getByRole('button', { name: 'Clear logs' }));
    expect(screen.getByRole('status').textContent).toContain('Lines: 0');
    expect(readLogState('p1').fileHashes).toEqual([]);
    expect(readLogState('p2').lines).toBe(30);
  });
  it('cancels an in-flight import, persists its offset, blocks another file and resumes exactly once', async () => {
    let release!: () => void;
    let entered = false;
    const gate = new Promise<void>((resolve) => { release = resolve; });
    const reader = vi.spyOn(files, 'readLogLines').mockImplementation(async function* () {
      yield logLine('/a');
      entered = true;
      await gate;
      yield logLine('/b');
    });
    render(<LogIntelligencePanel projectId="p1" />);
    const file = logFile([logLine('/a'), logLine('/b')].join('\n'));
    choose(file);
    await waitFor(() => expect(entered).toBe(true));
    expect((screen.getByRole('button', { name: 'Clear logs' }) as HTMLButtonElement).disabled).toBe(true);
    fireEvent.click(screen.getByRole('button', { name: 'Cancel' }));
    release();
    await screen.findByText(/Import cancelled\./);
    expect(readLogState('p1')).toMatchObject({ lines: 1, inProgress: { offset: 1 } });
    expect(screen.getByText('Select the same file to resume without counting lines twice.')).toBeTruthy();
    reader.mockRestore();
    choose(logFile(logLine('/different')));
    expect((await screen.findByRole('alert')).textContent).toContain('Resume the unfinished file');
    choose(file);
    await screen.findByText(/Import complete\./);
    expect(readLogState('p1')).toMatchObject({ lines: 2, inProgress: null });
    expect(Object.values(readLogState('p1').aggs).map((agg) => agg.hits)).toEqual([1, 1]);
  });
  it('shows qualified stored verdicts and paginates without dropping rows', () => {
    saveLogState('p1', coveredLogState());
    const paths: Array<[string, number]> = [['/a', 30], ...Array.from({ length: 51 }, (_, index): [string, number] => [`/z${String(index).padStart(2, '0')}`, 80])];
    render(<LogIntelligencePanel projectId="p1" run={logRun(paths)} />);
    expect(screen.getByText('Waste')).toBeTruthy();
    expect(screen.queryByText('Log coverage is insufficient for reliable verdicts.')).toBeNull();
    expect(screen.getByText('Page 1 of 2')).toBeTruthy();
    expect(screen.getAllByRole('row')).toHaveLength(51);
    fireEvent.click(screen.getByRole('button', { name: 'Next' }));
    expect(screen.getByText('/z50')).toBeTruthy();
    expect(screen.getByText('Page 2 of 2')).toBeTruthy();
    expect((screen.getByRole('button', { name: 'Next' }) as HTMLButtonElement).disabled).toBe(true);
    fireEvent.click(screen.getByRole('button', { name: 'Previous' }));
    fireEvent.click(screen.getByRole('button', { name: 'Clear logs' }));
    expect(screen.getAllByText('No logs')).toHaveLength(50);
  });
});
